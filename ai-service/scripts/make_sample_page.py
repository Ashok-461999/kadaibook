"""Render a synthetic khata page and its canonical label.

Everything here is invented: "KADAI STORES" and "Ravi Kumar" are fictional.
Use this page for demos, UI screenshots, and harness tests. Never substitute it
for a consented pilot page when reporting accuracy.
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "sample-data"
FIXTURE = REPO_ROOT / "ai-service" / "app" / "providers" / "mock_fixture.json"
PAGE_ID = "44444444-4444-4444-8444-444444444444"

WIDTH, HEIGHT = 1400, 2000
MARGIN = 90
INK = (28, 42, 68)
PAPER = (253, 250, 242)
RULE = (173, 186, 205)


def _font(size: int, *, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        Path("C:/Windows/Fonts/comicbd.ttf" if bold else "C:/Windows/Fonts/comic.ttf"),
        Path("C:/Windows/Fonts/segoeprb.ttf" if bold else "C:/Windows/Fonts/segoepr.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"),
        Path("/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf" if bold else "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf"),
    ]
    for path in candidates:
        if path.exists():
            return ImageFont.truetype(str(path), size)
    return ImageFont.load_default(size)


def _rupees(paise: int | None) -> str:
    if paise is None:
        return ""
    return f"{paise / 100:,.2f}"


def render(image_path: Path, label: dict) -> None:
    image = Image.new("RGB", (WIDTH, HEIGHT), PAPER)
    draw = ImageDraw.Draw(image)

    f_title = _font(58, bold=True)
    f_sub = _font(30)
    f_head = _font(30, bold=True)
    f_body = _font(36)
    f_small = _font(26)

    draw.text((MARGIN, 70), "KADAI STORES", font=f_title, fill=INK)
    draw.text((MARGIN, 145), "Hardware & building materials", font=f_sub, fill=INK)
    draw.text(
        (WIDTH - MARGIN - 430, 80),
        "SYNTHETIC SAMPLE - NOT REAL DATA",
        font=f_small,
        fill=(150, 70, 60),
    )

    draw.line((MARGIN, 210, WIDTH - MARGIN, 210), fill=INK, width=3)
    draw.text((MARGIN, 240), "Customer:", font=f_head, fill=INK)
    draw.text((MARGIN + 210, 238), label["customer_name"]["value"], font=f_body, fill=INK)
    draw.text((WIDTH - MARGIN - 250, 240), "Page: 1", font=f_sub, fill=INK)
    draw.text(
        (MARGIN, 300),
        f"Opening balance (b/f): Rs. {_rupees(label['opening_balance_paise'])}",
        font=f_sub,
        fill=INK,
    )

    columns = [MARGIN, MARGIN + 190, MARGIN + 650, MARGIN + 860, MARGIN + 1070, WIDTH - MARGIN]
    header_y = 380
    for x in columns:
        draw.line((x, header_y - 14, x, 1720), fill=RULE, width=2)
    draw.line((MARGIN, header_y - 14, WIDTH - MARGIN, header_y - 14), fill=INK, width=2)
    draw.line((MARGIN, header_y + 45, WIDTH - MARGIN, header_y + 45), fill=INK, width=2)
    for label_text, x in zip(
        ["Date", "Particulars", "Debit", "Credit", "Balance"],
        columns[:5],
        strict=False,
    ):
        draw.text((x + 14, header_y + 2), label_text, font=f_head, fill=INK)

    y = header_y + 80
    crossed_box = None
    for entry in label["entries"]:
        date_text = entry["date"] or ""
        if date_text:
            year, month, day = date_text.split("-")
            date_text = f"{day}/{month}/{year[2:]}"
        draw.text((columns[0] + 14, y), date_text, font=f_body, fill=INK)
        draw.text((columns[1] + 14, y), entry["description"] or "", font=f_body, fill=INK)
        draw.text((columns[2] + 14, y), _rupees(entry["debit_paise"]), font=f_body, fill=INK)
        draw.text((columns[3] + 14, y), _rupees(entry["credit_paise"]), font=f_body, fill=INK)
        draw.text(
            (columns[4] + 14, y),
            _rupees(entry["running_balance_paise"]),
            font=f_body,
            fill=INK,
        )
        if entry["entry_status"] == "crossed_out":
            crossed_box = (columns[1] + 5, y + 12, columns[4] + 210, y + 52)
        y += 92

    if crossed_box:
        draw.line(crossed_box, fill=(160, 45, 45), width=4)

    draw.line((MARGIN, y + 20, WIDTH - MARGIN, y + 20), fill=INK, width=2)
    draw.text(
        (columns[1] + 14, y + 50),
        "Closing balance",
        font=f_head,
        fill=INK,
    )
    draw.text(
        (columns[4] + 14, y + 50),
        f"Rs. {_rupees(label['closing_balance_paise'])}",
        font=f_head,
        fill=INK,
    )

    draw.text(
        (MARGIN, HEIGHT - 170),
        "Note: 20 kg rod entry was cancelled and struck out at the shop.",
        font=f_small,
        fill=(90, 90, 90),
    )
    draw.text(
        (MARGIN, HEIGHT - 130),
        "Synthetic page generated by KadaiBook. All names and amounts are fictional.",
        font=f_small,
        fill=(90, 90, 90),
    )

    image_path.parent.mkdir(parents=True, exist_ok=True)
    image.save(image_path, format="PNG", optimize=True)


def main() -> None:
    label = json.loads(FIXTURE.read_text(encoding="utf-8"))
    label["page_id"] = PAGE_ID
    image_path = OUT_DIR / "sample_customer_ledger.png"
    label_path = OUT_DIR / "sample_customer_ledger.expected.json"
    render(image_path, label)
    label_path.write_text(json.dumps(label, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = {
        "description": "Synthetic demo page. Not pilot data.",
        "pages": [
            {
                "page_id": PAGE_ID,
                "image": "sample_customer_ledger.png",
                "label": "sample_customer_ledger.expected.json",
            }
        ],
    }
    (OUT_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {image_path}")
    print(f"Wrote {label_path}")
    print(f"Wrote {OUT_DIR / 'manifest.json'}")


if __name__ == "__main__":
    main()
